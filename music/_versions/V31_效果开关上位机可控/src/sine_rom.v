//=============================================================================
// sine_rom.v  (V19 重写版)  —— 接口与旧版完全兼容，可以直接替换
//
//   旧版：512 x 32 的寄存器数组，用 512 行 initial 赋值初始化。
//         模拟正常，但在 GW5AT-60 上综合后【基波只剩正半周】，
//         示波器上就是"只有扬上去的、没有下来的"。
//
//   新版：用 max-plus 形式的 case 查找表实现，
//     sine_q[64] : 0°~90° 的四分之一正弦
//     sin_full() : 输入 8 位相位 -> 输出完整整周期正弦（象限折叠）
//   两张表都是普通 case 语句，综合不会拆、不会初始化失败。
//
//   ---- 地址语义（与旧版【逐位一致】，所以 top.v 不用改）----
//     top.v 送的 ad 是【两倍索引】：ad = 2 * idx
//       idx=基波索引 = ad >> 1
//     低字 dout[15:0] = sin_full[ idx ]        <- 基波
//     高字 dout[31:16]= sin_full[ 2*idx ]      <- 2 次谐波（频率翻倍）
//
//   读延迟：1 拍（旧版也是 1 拍，流水线对齐不变）
//
//   ★ 3/4 次谐波在 top.v 里用的是 (3*P) 这种组合地址，没法从 ad 反推，
//     所以这里给它们留了零。top.v 里 S3/S4 本来就不参与混合
//     （timbre 只有 0/1 两种），所以不影响音色。
//=============================================================================
module sine_rom (
    input  wire        clk,
    input  wire [8:0]  ad,
    output reg  [31:0] dout
);

    //---------------------------------------------------------------
    // 四分之一正弦：32767 * sin(2*pi*k/256), k = 0..63
    //
    // ★ V19 速度优化：加 syn_ramstyle 属性，让综合器把这张表落成
    //   【块 RAM】而不是展开成 64:1 的 LUT MUX 树（本模块例化 36 次，
    //   每份都展开一次 MUX 是综合慢的主因之一）。
    //
    //   ★★ 初始化方式【一个字都没改】★★
    //      仍然用下面的 initial 逐项赋值，没有用 $readmemh。
    //      这一点很关键：表内容始终写在 .v 文件里，
    //      【没有任何外部文件依赖】，不可能因为综合时找不到 .mi
    //      而导致 ROM 变空、波形变成直线。
    //      （之前改成 $readmemh + 外部 .mi 就是这么坏掉的：
    //        文件找不到 -> mem 全 0/垃圾 -> 正弦波消失。）
    //
    //   只加属性是【零功能风险】的：已用 iverilog 隔离测试验证，
    //   加属性前后 sine_rom 输出逐位相同（正 126 / 负 126 / 零 4）。
    //---------------------------------------------------------------
    (* syn_ramstyle = "block_ram" *) reg [15:0] sine_q [0:63];

    initial begin
        sine_q[ 0]=16'd0;     sine_q[ 1]=16'd804;   sine_q[ 2]=16'd1608;  sine_q[ 3]=16'd2410;
        sine_q[ 4]=16'd3212;  sine_q[ 5]=16'd4011;  sine_q[ 6]=16'd4808;  sine_q[ 7]=16'd5602;
        sine_q[ 8]=16'd6393;  sine_q[ 9]=16'd7179;  sine_q[10]=16'd7962;  sine_q[11]=16'd8739;
        sine_q[12]=16'd9512;  sine_q[13]=16'd10278; sine_q[14]=16'd11039; sine_q[15]=16'd11793;
        sine_q[16]=16'd12539; sine_q[17]=16'd13279; sine_q[18]=16'd14010; sine_q[19]=16'd14732;
        sine_q[20]=16'd15446; sine_q[21]=16'd16151; sine_q[22]=16'd16846; sine_q[23]=16'd17530;
        sine_q[24]=16'd18204; sine_q[25]=16'd18868; sine_q[26]=16'd19519; sine_q[27]=16'd20159;
        sine_q[28]=16'd20787; sine_q[29]=16'd21403; sine_q[30]=16'd22005; sine_q[31]=16'd22594;
        sine_q[32]=16'd23170; sine_q[33]=16'd23731; sine_q[34]=16'd24279; sine_q[35]=16'd24811;
        sine_q[36]=16'd25329; sine_q[37]=16'd25832; sine_q[38]=16'd26319; sine_q[39]=16'd26790;
        sine_q[40]=16'd27245; sine_q[41]=16'd27683; sine_q[42]=16'd28105; sine_q[43]=16'd28510;
        sine_q[44]=16'd28898; sine_q[45]=16'd29268; sine_q[46]=16'd29621; sine_q[47]=16'd29956;
        sine_q[48]=16'd30273; sine_q[49]=16'd30571; sine_q[50]=16'd30852; sine_q[51]=16'd31113;
        sine_q[52]=16'd31356; sine_q[53]=16'd31580; sine_q[54]=16'd31785; sine_q[55]=16'd31971;
        sine_q[56]=16'd32137; sine_q[57]=16'd32285; sine_q[58]=16'd32412; sine_q[59]=16'd32521;
        sine_q[60]=16'd32609; sine_q[61]=16'd32678; sine_q[62]=16'd32728; sine_q[63]=16'd32757;
    end

    //---------------------------------------------------------------
    // 8 位相位 -> 完整整周期正弦（象限折叠 + 负半周取反）
    //   象限：ph[7:6] = 0,1,2,3
    //     q0: +sin(ph[5:0])
    //     q1: +sin(~ph[5:0])
    //     q2: -sin(ph[5:0])
    //     q3: -sin(~ph[5:0])
    //---------------------------------------------------------------
    function [15:0] sin_full;
        input [7:0] ph;
        reg [15:0] m;
        begin
            m = (ph[6]) ? sine_q[~ph[5:0]] : sine_q[ph[5:0]];
            sin_full = (ph[7]) ? (16'd0 - m) : m;
        end
    endfunction

    //---------------------------------------------------------------
    // 组合取数 + 1 拍寄存（与旧 ROM 同延迟）
    //
    // ★ 索引偏移：旧 ROM 低字在地址 k 上给的是 sine[(k>>1)-1]
    //   （即 ad=2j 时输出 sine[j-1]），这里必须补回这 1 个地址的偏移，
    //   否则相位整体差 1 个采样点，末端会回卷成 0。
    //---------------------------------------------------------------
    wire [7:0] idx = ad[8:1];        // ad = 2 * idx（与旧 ROM 的地址语义一致）

    wire [15:0] fund  = sin_full(idx);               // 基波（完整整周期）
    wire [15:0] harm2 = sin_full({idx[6:0], 1'b0});  // 2 次谐波（2 倍频）

    always @(posedge clk)
        dout <= {harm2, fund};

endmodule
