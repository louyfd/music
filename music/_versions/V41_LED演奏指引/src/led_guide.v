//=============================================================================
// led_guide.v —— 36 颗 LED 的「演奏指引」（IS31FL3236A，第二路 I2C）
//
//   这一版（V41）是独立工程 D:\...\Documents\60k\LEDs 里已经【实机点亮确认】
//   的那份驱动的移植版。点亮用的初始化序列、逐寄存器写、`!done` 握手全部照搬，
//   只有"写什么亮度"从"固定全亮"改成了"跟着按键走"。
//
//-----------------------------------------------------------------------------
//   灯怎么亮
//-----------------------------------------------------------------------------
//     · 乐谱这一格要弹的键（midi_keys_aud）→ DUTY_SCORE（默认 0x28，暗）
//     · 手按下去的键（hand_mask）          → DUTY_HAND （默认 0xC0，亮）
//   两者同时成立时【手弹优先】——
//   于是"按对了键"会看到那颗灯由暗变亮，等于给了你一个即时回执。
//
//-----------------------------------------------------------------------------
//   ★★ 为什么整个模块跑在 clk_audio（12.5MHz）域上 ★★
//-----------------------------------------------------------------------------
//     · 它要用的两根输入 midi_keys_aud 和 hand_mask 【本来就已经在音频域】
//       （midi_keys_aud = midi_keys_s2，top.v 里早就做好了从 clk_50m_ext 过来的
//        两级同步；hand_mask 更是在音频域里生成的）。
//       → **不需要新增任何跨时钟同步**，一处都没有。
//     · 而 UART/LCD 那个域（clk_50m_ext）余量只剩 0.014%（V40 实测
//       50.007MHz / 约束 50MHz），往那儿加逻辑很危险。
//       音频域 Fmax 是 25.9MHz（2.07 倍余量），放这里最安全。
//     · I2C 需要的时钟只要 ≥ 400×SCL 就够：12.5MHz/100kHz = 125，够用。
//       QUARTER = 12_500_000/(100_000×4) = 31 → 实际 SCL ≈ 100.8kHz
//       （芯片上限 400kHz，和独立工程一样保守）。
//
//-----------------------------------------------------------------------------
//   ★ I2C 走的是【第二条总线】
//-----------------------------------------------------------------------------
//     ADS1115（摇杆）: i2c_scl = G22 / i2c_sda = V19   ← 主工程原有的
//     LED 指引       : led_scl = V17 / led_sda = W17   ← 本次新增，独立的两根线
//   两条总线互不影响，别搞混。
//
//-----------------------------------------------------------------------------
//   ★ 和独立工程那份驱动的两处差别（都是有意的）
//-----------------------------------------------------------------------------
//     1. 初始化里 36 笔 PWM 写的是 **0x00**（全灭）而不是 DUTY ——
//        上电不该先闪一下全亮，等初始化完第一轮扫描再按乐谱点亮。
//     2. 初始化完之后不是"挂起"，而是**每 5ms 比较一次**目标图案，
//        变了才发 I2C（36 笔 PWM + 1 笔 Update ≈ 10.6ms）。
//        图案没变时【一个字节都不发】，所以总线上平时是安静的。
//
//-----------------------------------------------------------------------------
//   ★★ 唯一需要你确认的地方：接线顺序映射 ch2key() ★★
//-----------------------------------------------------------------------------
//   见文件末尾的 ch2key()。现在假设 **LED 顺序 == TTP229 通道顺序**（恒等映射）。
//   验证办法（不需要改代码）：上电后逐个按琴键，看亮的是不是同一编号的灯。
//   如果不对，把 ch2key() 改成对应的置换表重新构建即可。
//   ★ 手弹键会直接点亮对应 LED，所以这个自检天然就有，不用另做测试模式。
//=============================================================================
`timescale 1ns / 1ps

module led_guide #(
    parameter integer CLK_HZ     = 12_500_000,   // ★ 本模块跑在 clk_audio 上
    parameter integer SCL_HZ     = 100_000,
    // ★ 7 位从机地址：由芯片 AD 引脚接法决定。本板实测 0x3C 可用（独立工程验过）。
    parameter [6:0]   DEV_ADDR   = 7'h3C,
    // ★ 亮度：0xFF 最亮。乐谱指引用暗一点，手弹用亮 —— 拉开对比才看得清"按对了"。
    parameter [7:0]   DUTY_SCORE = 8'h28,        // 乐谱这一格要弹的键（约 16%）
    parameter [7:0]   DUTY_HAND  = 8'hC0,        // 手按下的键（约 75%）
    // ★ PWM 频率：1 = 22kHz（高于音频，避免和琴声打拍/啸叫）
    parameter [7:0]   PWM_FREQ   = 8'h01,
    // 上电后等多久才开始碰 I2C（让芯片和电源稳定）
    parameter integer PWRUP_MS   = 50,
    // 两轮刷新之间至少隔多久（防止图案抖一下就连发几十笔）
    parameter integer SCAN_MS    = 5
)(
    input  wire        clk,
    input  wire        rst_n,

    // ---- 要显示的图案（都在本时钟域，不需要同步）----
    input  wire [35:0] score_keys,   // 乐谱：当前时间格要点亮的键（midi_keys_aud）
    input  wire [35:0] hand_keys,    // 手弹：物理按键（hand_mask）

    // ---- 第二路 I2C（到 IS31FL3236A）----
    output wire        led_scl,
    inout  wire        led_sda
);

    //-------------------------------------------------------------------------
    // 时间常数
    //-------------------------------------------------------------------------
    localparam integer PWRUP_CYC = (CLK_HZ / 1000) * PWRUP_MS;
    localparam integer SCAN_CYC  = (CLK_HZ / 1000) * SCAN_MS;

    // 初始化一共 76 笔：
    //   0        0x4F = 0x00   复位所有寄存器
    //   1  ~ 36  0x26+i = 0x01 LED Control：开通道 + IMAX
    //   37 ~ 72  0x01+i = 0x00 PWM 全灭（等第一轮扫描再点）
    //   73       0x25 = 0x00   ★ PWM Update：影子寄存器必须写它才生效
    //   74       0x4B = freq   PWM 输出频率
    //   75       0x00 = 0x01   ★ SSD=1 退出软件关断
    localparam [6:0] INIT_LAST = 7'd75;

    //-------------------------------------------------------------------------
    // 相位
    //-------------------------------------------------------------------------
    //   ★ Verilog 的声明列表只在第一项前写一次 localparam，后面几项【不能再写】
    //     （写了就是 EX3863 / EX2656「Verilog 2001 keyword used in incorrect context」）。
    localparam [2:0] PH_PWR  = 3'd0,   // 上电延时
                     PH_INIT = 3'd1,   // 76 笔初始化
                     PH_WAIT = 3'd2,   // 等图案变化（同时保证最小间隔）
                     PH_SCAN = 3'd3,   // 逐路写 PWM
                     PH_UPD  = 3'd4;   // 写一次 Update 让影子寄存器生效

    reg [2:0]  ph;
    reg [6:0]  step;        // PH_INIT 的笔号 / PH_SCAN 的通道号
    reg [31:0] pwr_cnt;
    reg [31:0] gap_cnt;

    // ★ 上一轮【实际发出去】的原始图案快照。
    //   它同时充当两件事：
    //     ① "图案变了吗"的比较基准（没变就一个字节都不发）
    //     ② 扫描期间的数据源（扫描中途输入变了也不会写出半新半旧的图案）
    //   ★ 所以它只需要 72 个触发器，不用再存一份"映射后的"。
    reg [71:0] snap_pat;

    reg        go;
    reg [7:0]  reg_a;
    reg [7:0]  dat;
    wire       busy, done, nack;

    //-------------------------------------------------------------------------
    // ★★★ 接线顺序映射 —— 唯一需要你确认的地方 ★★★
    //
    //   ch2key(c) = 第 c 路 LED（芯片 OUT{c+1}）对应琴上的哪个键（0..35）
    //
    //   现在返回 c，即假设 **LED 顺序 == TTP229 通道顺序**（恒等映射）。
    //   ★ 验证办法（不用改代码）：上电后逐个按琴键，看亮的是不是同一个编号的灯。
    //     手弹键会直接点亮对应 LED，所以自检天然就有，不用另做测试模式。
    //   ★ 如果顺序不对：按你实测的对应关系改下面的 case 即可，别的地方不用动。
    //     例：若"第 0 路 LED 其实接的是键 5"，就写 6'd0: ch2key = 6'd5;
    //
    //   ★ 为什么用 function + case 而不是 216 位的常数向量：常数下标调用会被
    //     综合器【常数折叠】掉，一点 LUT 都不烧；而宽向量动态位选反而要一大片
    //     选择器（交接文档坑 5/13 都是这类）。函数必须声明在调用点之前。
    //-------------------------------------------------------------------------
    function [5:0] ch2key;
        input [5:0] c;
        begin
            case (c)
                6'd0 : ch2key = 6'd0;    6'd1 : ch2key = 6'd1;
                6'd2 : ch2key = 6'd2;    6'd3 : ch2key = 6'd3;
                6'd4 : ch2key = 6'd4;    6'd5 : ch2key = 6'd5;
                6'd6 : ch2key = 6'd6;    6'd7 : ch2key = 6'd7;
                6'd8 : ch2key = 6'd8;    6'd9 : ch2key = 6'd9;
                6'd10: ch2key = 6'd10;   6'd11: ch2key = 6'd11;
                6'd12: ch2key = 6'd12;   6'd13: ch2key = 6'd13;
                6'd14: ch2key = 6'd14;   6'd15: ch2key = 6'd15;
                6'd16: ch2key = 6'd16;   6'd17: ch2key = 6'd17;
                6'd18: ch2key = 6'd18;   6'd19: ch2key = 6'd19;
                6'd20: ch2key = 6'd20;   6'd21: ch2key = 6'd21;
                6'd22: ch2key = 6'd22;   6'd23: ch2key = 6'd23;
                6'd24: ch2key = 6'd24;   6'd25: ch2key = 6'd25;
                6'd26: ch2key = 6'd26;   6'd27: ch2key = 6'd27;
                6'd28: ch2key = 6'd28;   6'd29: ch2key = 6'd29;
                6'd30: ch2key = 6'd30;   6'd31: ch2key = 6'd31;
                6'd32: ch2key = 6'd32;   6'd33: ch2key = 6'd33;
                6'd34: ch2key = 6'd34;   6'd35: ch2key = 6'd35;
                //   ★ default 故意回 0（不是回 c）：扫描到 step=36 时已经不发事务了，
                //     但 scan_key 是组合算出来的，回 c 会得到 36 →
                //     snap_pat[36+36]=snap_pat[72] 越界（72 位向量只到 71）。
                //     回 0 保证索引永远落在 0..35。全部 36 个值上面都列全了。
                default: ch2key = 6'd0;
            endcase
        end
    endfunction

    //-------------------------------------------------------------------------
    // 当前扫描到的那一路，应该是什么亮度
    //-------------------------------------------------------------------------
    wire [5:0] scan_key   = ch2key(step[5:0]);          // 这一路 LED 对应哪个键
    wire       scan_hand  = snap_pat[36 + scan_key];    // 手弹？
    wire       scan_score = snap_pat[scan_key];         // 乐谱？
    wire [7:0] scan_duty  = scan_hand  ? DUTY_HAND :
                            (scan_score ? DUTY_SCORE : 8'h00);

    // 图案和"上一轮发出去的"不一样吗
    wire pat_changed = ({hand_keys, score_keys} != snap_pat);

    //-------------------------------------------------------------------------
    // (相位, step) → (寄存器地址, 数据)
    //-------------------------------------------------------------------------
    always @(*) begin
        if (ph == PH_UPD) begin
            reg_a = 8'h25;  dat = 8'h00;                  // ★ PWM Update
        end else if (ph == PH_SCAN) begin
            reg_a = 8'h01 + {1'b0, step[5:0]};            // 通道 step+1 → 0x01..0x24
            dat   = scan_duty;
        end else if (step == 7'd0) begin
            reg_a = 8'h4F;  dat = 8'h00;                  // 复位
        end else if (step <= 7'd36) begin
            reg_a = 8'h26 + {1'b0, step} - 8'd1;          // LED Control 0x26..0x49
            dat   = 8'h01;                                // D0=1 开通道, D2:D1=00 IMAX
        end else if (step <= 7'd72) begin
            reg_a = 8'h01 + {1'b0, step} - 8'd37;         // PWM 0x01..0x24
            dat   = 8'h00;                                // ★ 初始化时全灭
        end else if (step == 7'd73) begin
            reg_a = 8'h25;  dat = 8'h00;                  // ★ PWM Update
        end else if (step == 7'd74) begin
            reg_a = 8'h4B;  dat = PWM_FREQ;               // PWM 输出频率
        end else begin
            // step == 75：★ SSD=1 退出软件关断
            // ★★ step > 75 是"不该发生"的地址，这里【故意也返回 SSD=1】★★
            //   独立工程里踩过：那个 else 返回 SSD=0（软件关断）时，
            //   配上多发的一笔 go 就是"全部 LED 亮一瞬间就灭了"。
            reg_a = 8'h00;  dat = 8'h01;
        end
    end

    //-------------------------------------------------------------------------
    // 主状态机
    //
    //   ★★★ 每个"发起事务"的地方都必须带 !done ★★★
    //     主机的 done 脉冲和 busy<=0 是同一拍生效的 —— done 那一拍 busy 已经是 0；
    //     而 step 要到【那一拍结束】才 +1。少了 !done，done 那一拍会拿旧的 step
    //     再排一笔 go，下一拍 step 已经 +1，于是一共多发一笔事务。
    //     独立工程里就是这一条造成"全部 LED 亮一瞬间就灭了"（那一笔写到 SSD=0）。
    //     ★ testfiles\sim_led_guide.py 里有一条断言专门钉这个不变量，
    //       改动本块后请重跑它。
    //-------------------------------------------------------------------------
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            go       <= 1'b0;
            ph       <= PH_PWR;
            step     <= 7'd0;
            pwr_cnt  <= 32'd0;
            gap_cnt  <= 32'd0;
            snap_pat <= 72'd0;
        end else begin
            go <= 1'b0;                       // 默认拉低 → go 只可能是一拍脉冲

            case (ph)
                //----------------------------------------------------------
                // 上电延时：让芯片和电源先稳定再碰 I2C
                //   ★ 这段【必须在同一个 always 块里】—— ph 是同一个寄存器，
                //     拆到第二个 always 块会变成"两块驱动同一 reg" = EX2000
                //     （交接文档坑 1 就是这个）。
                PH_PWR: begin
                    if (pwr_cnt >= PWRUP_CYC[31:0]) ph <= PH_INIT;
                    else                            pwr_cnt <= pwr_cnt + 32'd1;
                end
                PH_INIT: begin
                    if (!busy && !go && !done) begin
                        if (step <= INIT_LAST) go <= 1'b1;
                        else begin ph <= PH_WAIT; gap_cnt <= 32'd0; end
                    end
                    if (done) step <= step + 7'd1;
                end
                //----------------------------------------------------------
                // 等图案变化。★ 图案没变就一直等，一个字节都不发。
                //   gap_cnt 到顶就停住（饱和），所以图案一变就能立刻走。
                PH_WAIT: begin
                    if (pat_changed && gap_cnt >= SCAN_CYC[31:0]) begin
                        gap_cnt  <= 32'd0;
                        // ★ 锁存这一轮的图案：扫描期间输入再变，
                        //   也是等这一轮写完、下一轮再处理（pat_changed 会再次成立）
                        snap_pat <= {hand_keys, score_keys};
                        step     <= 7'd0;
                        ph       <= PH_SCAN;
                    end else if (gap_cnt < SCAN_CYC[31:0]) begin
                        gap_cnt <= gap_cnt + 32'd1;
                    end
                end
                //----------------------------------------------------------
                // 逐路写 PWM：0x01..0x24 共 36 笔
                PH_SCAN: begin
                    if (!busy && !go && !done) begin
                        if (step <= 7'd35) go <= 1'b1;
                        else               ph <= PH_UPD;
                    end
                    if (done) step <= step + 7'd1;
                end
                //----------------------------------------------------------
                // 最后写一次 Update，36 路新亮度同时生效
                PH_UPD: begin
                    if (!busy && !go && !done) go <= 1'b1;
                    if (done) begin
                        ph      <= PH_WAIT;
                        gap_cnt <= 32'd0;
                    end
                end
                default: ph <= PH_PWR;
            endcase
        end
    end

    //-------------------------------------------------------------------------
    // I2C 主机（和独立工程 LEDs\src\i2c_master.v 逐字相同，那边的 21 项逐拍
    // 仿真全过，包括一个 STOP 相位的真 bug）
    //-------------------------------------------------------------------------
    i2c_master #(
        .CLK_HZ (CLK_HZ),
        .SCL_HZ (SCL_HZ)
    ) u_i2c (
        .clk   (clk),
        .rst_n (rst_n),
        .go    (go),
        .dev   (DEV_ADDR),
        .reg_a (reg_a),
        .dat   (dat),
        .busy  (busy),
        .done  (done),
        .nack  (nack),
        .scl   (led_scl),
        .sda   (led_sda)
    );

endmodule
